#!/bin/sh
# The gate: every cancho test of the models, the generator and the host, then the generated hardware against them (gen/check.sh).
# Needs the cancho compiler (CANCHO=path, default ../cancho/target/release/cancho), Icarus Verilog and Yosys. Exits non-zero on any failure.
set -e
cd "$(dirname "$0")"
CANCHO=${CANCHO:-../cancho/target/release/cancho}
export CANCHO
MODS="$(ls sim/*.cho) host/regs.cho gen/ir.cho gen/pid_ir.cho gen/raster_ir.cho gen/lockin_ir.cho host/proto.cho host/twin_link.cho host/script.cho host/run_twin.cho host/session.cho host/image.cho host/metrics.cho host/features.cho host/drift.cho host/report.cho host/png.cho host/force.cho host/align.cho"
fail=0
for t in tests/*_test.cho; do
  out=$($CANCHO test "$t" $MODS --std 2>&1) || true
  line=$(echo "$out" | grep "test result" | head -1)
  printf '%-34s %s\n' "$(basename "$t")" "${line:-NO RESULT: $(echo "$out" | head -1)}"
  echo "$line" | grep -q " 0 failed" || fail=1
done
[ "$fail" = 0 ] || { echo "cancho tests FAILED"; exit 1; }
sh gen/check.sh > /dev/null
echo "gen/check.sh (generated hardware against the models): passed"
# the identifier is written in three places (the Verilog register file, the twin and the host); a wrong decimal copy once passed every test and would have
# refused the real board, so they must all say 0xAF500001
grep -q "32'hAF500001" gen/glue.cho
grep -q "0xAF500001" sim/board.cho
grep -q "0xAF500001" host/session.cho
grep -q "0xAF500001" host/tty_run.cho
echo "identifier 0xAF500001 agrees in the Verilog, the twin and the host: passed"
# generated artifacts must equal the committed ones (a stale generated file is a bug)
$CANCHO run gen/regs_chw.cho host/regs.cho --std > /tmp/afm_chw.new
cmp -s /tmp/afm_chw.new hw/afm.chw || { echo "hw/afm.chw is stale: regenerate it with gen/regs_chw.cho"; exit 1; }
$CANCHO run gen/regs_doc.cho host/regs.cho --std > /tmp/afm_table.new
cmp -s /tmp/afm_table.new docs/registers-table.md || { echo "docs/registers-table.md is stale: regenerate it with gen/regs_doc.cho"; exit 1; }
rm -f /tmp/afm_chw.new /tmp/afm_table.new
echo "hw/afm.chw and docs/registers-table.md are up to date with host/regs.cho: passed"
# optional: with CHW set to a built cancho-hdl `chw` (see ../cancho-hdl/scripts/build.sh) and CHW_DIR its repository, the contract is checked by chw and the C header compared
if [ -n "${CHW:-}" ]; then
  cp hw/afm.chw /tmp/afm.chw
  ( cd "${CHW_DIR:-../cancho-hdl}" && "$CHW" check /tmp/afm.chw > /dev/null && "$CHW" generate /tmp/afm.chw --target c-header | sed '1s|.*|/* Generated by cancho-hdl from hw/afm.chw. Do not edit. */|' > /tmp/afm.h.new )
  cmp -s /tmp/afm.h.new hw/afm.h || { echo "hw/afm.h is stale: regenerate it (docs/registers.md)"; exit 1; }
  rm -f /tmp/afm.chw /tmp/afm.h.new
  echo "chw check accepts hw/afm.chw and hw/afm.h is up to date: passed"
fi
# optional: with KICAD_CLI set to kicad-cli, the schematic is checked by KiCad's ERC and against the simulated circuits
if [ -n "${KICAD_CLI:-}" ]; then
  sh hw/kicad/check.sh > /dev/null
  echo "hw/kicad schematic: generator, ERC and nets against the simulation: passed"
fi
# the alignment steps and the force in the report, against the twin (S9.7); needs only the compiler
sh tests/liquid_flow.sh
# the scan -> particles.csv -> cancho-table flow (I3) needs a built `table`; it runs only when TABLE names one
if [ -n "${TABLE:-}" ]; then
  sh tests/particles_flow.sh
else
  echo "particles flow: skipped (set TABLE to a built cancho-table)"
fi
